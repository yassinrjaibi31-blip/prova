/*
Questa classe rappresenta uno studente di una scuola
Questo e il primo esempio
 */
public class Studente {
    String nome;
    String cognome;
    int eta;
    float altezza;
    float peso;
    /*
    questo é il costrutore
     */
    public Studente(String nome,String cognome,int eta,float altezza,float peso){
        this.nome=nome;
        this.cognome=cognome;
        this.eta=eta;
        this.altezza=altezza;
        this.peso=peso;
    }
}
