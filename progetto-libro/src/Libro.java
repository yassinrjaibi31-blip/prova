public class Libro {
    private String titolo;
    private String autore;
    private int pagine;
    private float prezzo;
    private String ISBN;

    public Libro
            (String titolo,
             String autore,
             int pagine,
             float prezzo,
             String ISBN){
        this.titolo=titolo;
        this.autore=autore;
        this.pagine=pagine;
        this.prezzo=prezzo;
        this.ISBN=ISBN;
    }



}
